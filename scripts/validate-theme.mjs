test("21 public commerce remains disabled",async()=>{const config=await read("src/config/site.ts");const gate=await read("src/features/storefront/config.ts");assert.match(config,/commerceEnabled:\s*false/);assert.match(gate,/STOREFRONT_TEST_MODE\s*===\s*"true"/);});

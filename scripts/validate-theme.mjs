import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";

execFileSync(process.execPath,["node_modules/typescript/bin/tsc","-p","tsconfig.theme-tests.json"],{stdio:"inherit"});
await writeFile(new URL("../.theme-test-build/package.json",import.meta.url),'{"type":"commonjs"}\n');
const require=createRequire(import.meta.url);
const {normalizeThemeMode,resolveTheme,themeInitializationScript,themeStorageKey}=require("../.theme-test-build/theme.js");
const read=(path)=>readFile(new URL(`../${path}`,import.meta.url),"utf8");
const tests=[];const test=(name,run)=>tests.push([name,run]);
test("01 storage key",()=>assert.equal(themeStorageKey,"haribol-theme"));
test("02 no value becomes System",()=>assert.equal(normalizeThemeMode(null),"system"));
test("03 malformed value becomes System",()=>assert.equal(normalizeThemeMode("sepia"),"system"));
test("04 System on light OS",()=>assert.equal(resolveTheme("system",false),"light"));
test("05 System on dark OS",()=>assert.equal(resolveTheme("system",true),"dark"));
test("06 Light overrides dark OS",()=>assert.equal(resolveTheme("light",true),"light"));
test("07 Dark overrides light OS",()=>assert.equal(resolveTheme("dark",false),"dark"));
test("08 System remains a preference",()=>assert.equal(normalizeThemeMode("system"),"system"));
test("09 Light persists as a preference",()=>assert.equal(normalizeThemeMode("light"),"light"));
test("10 Dark persists as a preference",()=>assert.equal(normalizeThemeMode("dark"),"dark"));
test("11 pre-hydration script resolves before body",()=>assert.match(themeInitializationScript,/document\.documentElement/));
test("12 script stores preference separately",()=>assert.match(themeInitializationScript,/themePreference/));
test("13 script size is constrained",()=>assert.ok(Buffer.byteLength(themeInitializationScript)<600));
test("14 website layout owns script",async()=>assert.match(await read("src/app/(website)/layout.tsx"),/themeInitializationScript/));
test("15 Payload layout isolated",async()=>assert.doesNotMatch(await read("src/app/(payload)/layout.tsx"),/theme|globals\.css/));
test("16 desktop control",async()=>assert.match(await read("src/components/layout/site-header.tsx"),/placement="desktop"/));
test("17 mobile control",async()=>assert.match(await read("src/components/layout/site-header.tsx"),/placement="mobile"/));
test("18 screen reader semantics",async()=>{const s=await read("src/components/ui/theme-control.tsx");assert.match(s,/menuitemradio/);assert.match(s,/aria-checked/);});
